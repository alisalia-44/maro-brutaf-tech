create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text not null default 'android',
  brand text not null,
  model text not null,
  condition_label text not null default 'neuf',
  description text not null default '',
  image_url text not null default '',
  specs jsonb not null default '{}'::jsonb,
  capacities jsonb not null default '[]'::jsonb,
  colors jsonb not null default '[]'::jsonb,
  is_new boolean not null default false,
  trade_in boolean not null default false,
  is_visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  id integer primary key default 1 check (id = 1),
  store_name text not null default 'MARO BRUTAF TECH',
  whatsapp text not null default '',
  address text not null default '',
  opening_hours text not null default '',
  about_title text not null default '',
  about_text text not null default '',
  announcement text not null default '',
  facebook_url text not null default '',
  instagram_url text not null default '',
  updated_at timestamptz not null default now()
);

-- Liste des comptes autorisés à administrer la boutique.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admin_users where user_id = (select auth.uid()));
$$;

alter table public.products enable row level security;
alter table public.store_settings enable row level security;
alter table public.admin_users enable row level security;

drop policy if exists "Public can read visible products" on public.products;
create policy "Public can read visible products" on public.products
  for select to anon, authenticated using (is_visible = true or public.is_store_admin());

drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products
  for all to authenticated using (public.is_store_admin()) with check (public.is_store_admin());

drop policy if exists "Public can read store settings" on public.store_settings;
create policy "Public can read store settings" on public.store_settings
  for select to anon, authenticated using (true);

drop policy if exists "Admins manage store settings" on public.store_settings;
create policy "Admins manage store settings" on public.store_settings
  for all to authenticated using (public.is_store_admin()) with check (public.is_store_admin());

-- L'accès à admin_users n'est pas exposé au public; seuls les administrateurs peuvent lire la liste.
drop policy if exists "Admins can read admin list" on public.admin_users;
create policy "Admins can read admin list" on public.admin_users
  for select to authenticated using (public.is_store_admin());

